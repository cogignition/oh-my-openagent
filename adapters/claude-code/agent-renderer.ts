// Renders omo built-in agents as ~/.claude/agents/omo-{name}.md files for Claude Code.

import { mkdirSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { join } from 'node:path'
import { createBuiltinAgents } from '../../src/agents/builtin-agents.js'

export interface RenderOmoAgentsOpts {
  quickModel: string  // e.g. 'lmstudio/google/gemma-4-26b-a4b' — provider prefix stripped on write
  deepModel: string   // e.g. 'anthropic/claude-opus-4-6' — provider prefix stripped on write
  directory?: string
  outDir?: string
}

// Agents that should use the quick/subagent model
const QUICK_AGENTS = new Set(['sisyphus-junior', 'explore', 'librarian', 'metis', 'momus'])

// Agents to skip entirely (require capabilities not available in all environments)
const SKIP_AGENTS = new Set(['multimodal-looker'])

/**
 * Strip provider prefix from a model ID so Claude Code can use it directly.
 * 'lmstudio/google/gemma-4-26b-a4b' → 'google/gemma-4-26b-a4b'
 * 'anthropic/claude-opus-4-6'       → 'claude-opus-4-6'
 */
function stripProviderPrefix(model: string): string {
  const knownPrefixes = ['lmstudio', 'anthropic', 'openai', 'google', 'mistral', 'ollama']
  const firstSegment = model.split('/')[0]
  if (knownPrefixes.includes(firstSegment)) {
    return model.split('/').slice(1).join('/')
  }
  return model
}

export async function renderOmoAgents(opts: RenderOmoAgentsOpts): Promise<void> {
  const { quickModel, deepModel, directory } = opts
  const outDir = opts.outDir ?? join(homedir(), '.claude', 'agents')

  mkdirSync(outDir, { recursive: true })

  const agents = await createBuiltinAgents([], {}, directory, deepModel)

  for (const [name, config] of Object.entries(agents)) {
    if (SKIP_AGENTS.has(name)) continue

    try {
      const model = QUICK_AGENTS.has(name)
        ? stripProviderPrefix(quickModel)
        : stripProviderPrefix(deepModel)

      const frontmatter = [
        '---',
        `name: omo-${name}`,
        `description: "${(config.description ?? '').replace(/"/g, '\\"')}"`,
        `model: ${model}`,
        '---',
      ].join('\n')

      const content = [
        '# Generated by omo adapter — do not edit manually',
        frontmatter,
        '',
        config.prompt,
      ].join('\n')

      const outPath = join(outDir, `omo-${name}.md`)
      writeFileSync(outPath, content, 'utf8')
    } catch (err) {
      console.error(`[agent-renderer] Failed to render agent "${name}":`, err)
    }
  }
}
